/**
 * EXPORT DEBUGGER
 *
 * Run this in your console to see what's failing
 */

console.log('%c🔍 Diagnosing Export Issue...', 'color: #F59E0B; font-size: 14px; font-weight: bold');

// Check if Monitor Pro is loaded
if (!window.__WEBFLOW_MONITOR_PRO__) {
  console.error('❌ Monitor Pro is not loaded!');
  console.log('Load Monitor Pro first, then run this diagnostic again.');
} else {
  console.log('✅ Monitor Pro is loaded');

  // Find the monitor instance
  const host = document.getElementById('webflow-monitor-pro-host');
  if (!host) {
    console.error('❌ Cannot find monitor host element');
  } else {
    console.log('✅ Found monitor host');

    const exportBtn = host.shadowRoot?.querySelector('.wm-export-btn');
    if (!exportBtn) {
      console.error('❌ Cannot find export button');
    } else {
      console.log('✅ Found export button');

      // Try to manually export with better error handling
      console.log('\n%c📊 Attempting manual export...', 'color: #6366F1; font-weight: bold');

      try {
        // Get all the data we can find
        const performanceData = performance.getEntriesByType('navigation')[0];
        const resources = performance.getEntriesByType('resource');

        const report = {
          timestamp: new Date().toISOString(),
          url: window.location.href,
          userAgent: navigator.userAgent,
          viewport: {
            width: window.innerWidth,
            height: window.innerHeight
          },
          performance: {
            navigation: performanceData ? {
              loadTime: Math.round(performanceData.loadEventEnd - performanceData.fetchStart),
              domContentLoaded: Math.round(performanceData.domContentLoadedEventEnd - performanceData.fetchStart),
              ttfb: Math.round(performanceData.responseStart - performanceData.requestStart)
            } : null,
            resources: resources.map(r => ({
              name: r.name.split('/').pop(),
              type: r.initiatorType,
              size: r.transferSize || 0,
              duration: Math.round(r.duration)
            }))
          },
          dom: {
            elements: document.querySelectorAll('*').length,
            scripts: document.scripts.length,
            styles: document.styleSheets.length
          },
          errors: window.console.errors || [],
          note: 'Generated by diagnostic export'
        };

        console.log('Data prepared:', report);

        // Try to create and download
        const jsonStr = JSON.stringify(report, null, 2);
        console.log('✅ JSON stringified successfully');

        const blob = new Blob([jsonStr], { type: 'application/json' });
        console.log('✅ Blob created');

        const url = URL.createObjectURL(blob);
        console.log('✅ Object URL created');

        const a = document.createElement('a');
        a.href = url;
        a.download = `webflow-diagnostic-${Date.now()}.json`;

        // Must append to body for Firefox
        document.body.appendChild(a);
        a.click();
        console.log('✅ Download triggered');

        // Cleanup
        setTimeout(() => {
          document.body.removeChild(a);
          URL.revokeObjectURL(url);
        }, 100);

        console.log('%c✅ Export succeeded!', 'color: #10B981; font-weight: bold; font-size: 14px');
        console.log('Check your downloads folder for: webflow-diagnostic-[timestamp].json');

      } catch (error) {
        console.error('%c❌ Export failed with error:', 'color: #EF4444; font-weight: bold');
        console.error('Error name:', error.name);
        console.error('Error message:', error.message);
        console.error('Error stack:', error.stack);

        console.log('\n%c🔧 Possible causes:', 'color: #F59E0B; font-weight: bold');
        console.log('1. Browser blocking downloads (check download permissions)');
        console.log('2. Data contains circular references');
        console.log('3. JSON.stringify failing on complex objects');
        console.log('4. Browser security policy blocking blob downloads');
      }
    }
  }
}

console.log('\n%cWhat to do next:', 'color: #6366F1; font-weight: bold');
console.log('1. Look for RED error messages above');
console.log('2. Copy the error message');
console.log('3. Share it so we can fix the exact issue');
